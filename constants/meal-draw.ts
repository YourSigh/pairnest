export const MEAL_OPTIONS: MealOption[] = MEAL_GROUPS.flatMap(
  (group, groupIndex) =>
    group.names.map((name, itemIndex) => ({
      id: `meal-${groupIndex + 1}-${itemIndex + 1}`,
      name,
      emoji: group.emoji,
      category: group.category,
      cuisine: group.cuisine,
      moods: [...group.moods],
      scenes: [...group.scenes],
      reason: group.reason,
    })),
);

export function createMealShareText(meal: MealOption) {
  return [
    `🍽️ 饭点盲盒抽到了：${meal.name}`,
    `${meal.emoji} ${meal.category} · ${meal.cuisine}`,
    `“${meal.reason}”`,
    "要不要就吃这个？",
  ].join("\n");
}
